/**
 * Chart / page export functions — ported verbatim from the CR3 reference
 * (Rebh_CR3_reference/pro_dashboard_template.html lines 288-324).
 *
 * The reference drives these off module globals (DATA, S, rangeState, stacks,
 * t, PREFS, css). Here every entry point takes the live ChartHub (which owns
 * data + the shared range + colour resolution) and the concrete panels, so the
 * behaviour is identical while staying importable from React and from the
 * imperative Stack engine alike.
 */
