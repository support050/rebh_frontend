/** A rendered panel: the canvas + its DOM div + the panel definition fields. */
export interface ExportPanel {
  canvas: HTMLCanvasElement;
  div: HTMLElement;
  title?: string;
  series: SeriesDef[];
  hlines?: HLineDef[];
  mini?: boolean;
}

/** Trigger a browser download for a blob and release the object URL. */
export function downloadBlob(blob: Blob, name: string): void {
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 3000);
}

const safe = (s: string): string => s.replace(/[^a-z0-9]+/gi, '_').slice(0, 40);

/** CSV cell: quote anything containing , " or newline (string series such as
 *  bpi_status would otherwise shift/corrupt the row). */
function csvCell(v: unknown): string {
  if (v == null) return '';
  const s = String(v);
  return /[',"\n\r]/.test(s) ? `"${s.replace(/"/g, "'")}"` : s;
}

/** Deduped, ordered list of series keys across the given panels (reference seriesOf). */
function seriesOf(hub: ChartHub, panels: ExportPanel[]): { key: string; label: string }[] {
  const ks: { key: string; label: string }[] = [];
  panels.forEach((p) =>
    p.series.forEach((x) => {
      if (!ks.find((k) => k.key === x.key)) ks.push({ key: x.key, label: x.label || x.key });
    }),
  );
  return ks.filter((k) => Array.isArray(hub.data.series[k.key]));
}

/* ---------------------------------- CSV ------------------------------------ */

/**
 * exportCSV — TradingView layout: time,open,high,low,close,volume + one column
 * per visible series, sliced to the current range (reference lines 301-303).
 */
export function exportCSV(hub: ChartHub, panels: ExportPanel[], name: string): void {
  const ks = seriesOf(hub, panels);
  const { i0, i1 } = hub.range;
  const S = hub.data.series;
  const header =
    'time,open,high,low,close,volume,' + ks.map((k) => `"${k.label.replace(/"/g, "'")}"`).join(',');
  const rows = [header];
  for (let i = i0; i <= i1; i++) {
    rows.push(
      [
        hub.data.dates[i],
        S.tasi_o?.[i],
        S.tasi_h?.[i],
        S.tasi_l?.[i],
        S.tasi?.[i],
        S.tasi_vol?.[i],
        ...ks.map((k) => S[k.key]?.[i]),
      ]
        .map(csvCell)
        .join(','),
    );
  }
  downloadBlob(
    new Blob(['\ufeff' + rows.join('\n')], { type: 'text/csv;charset=utf-8' }),
    `TASI_breadth_${safe(name)}_${hub.data.dates[i0]}_${hub.data.dates[i1]}.csv`,
  );
}

/* ------------------------------ Pine Script -------------------------------- */

const PINE_COLS = [
  'color.new(color.blue,0)', 'color.new(color.orange,0)', 'color.new(color.teal,0)',
  'color.new(color.purple,0)', 'color.new(color.red,0)', 'color.new(color.green,0)',
  'color.new(color.gray,0)', 'color.new(color.yellow,0)',
];

/**
 * exportPine — a self-contained Pine v5 indicator that replays the page's
 * numeric series on TADAWUL:TASI by date-keyed maps (reference lines 304-310).
 * Honours PREFS.tvbars for how many trailing bars to embed.
 */
export function exportPine(hub: ChartHub, panels: ExportPanel[], name: string, todayDate: string): void {
  const S = hub.data.series;
  const N = hub.data.dates.length;
  const ks = seriesOf(hub, panels)
    .filter((k) => typeof (S[k.key].find((v) => v != null) as number) === 'number')
    .slice(0, 8);
  const n = Math.min(getPrefs().tvbars, N);
  const i0 = N - n;
  const L: string[] = [];
  L.push('//@version=5');
  L.push(`indicator("TASI Breadth — ${name.replace(/"/g, "'").slice(0, 60)}", overlay=false, max_bars_back=5000)`);
  L.push(`// Generated by the TASI Market Breadth engine (rebh.ai) on ${todayDate}. Apply to TADAWUL:TASI, daily. Values are keyed by date (YYYYMMDD).`);
  L.push('key = year*10000 + month*100 + dayofmonth');
  ks.forEach((k, j) => {
    const v = `m${j}`;
    L.push(`var ${v} = map.new<int,float>()`);
    L.push('if barstate.isfirst');
    for (let i = i0; i < N; i++) {
      const val = S[k.key][i];
      if (val == null) continue;
      L.push(`    map.put(${v}, ${hub.data.dates[i].replace(/-/g, '')}, ${val})`);
    }
    L.push(`s${j} = map.contains(${v}, key) ? map.get(${v}, key) : na`);
    L.push(`plot(s${j}, "${k.label.replace(/"/g, "'")}", color=${PINE_COLS[j % PINE_COLS.length]}, linewidth=${j === 0 ? 2 : 1})`);
  });
  const hl: number[] = [];
  panels.forEach((p) => (p.hlines || []).forEach((h) => { if (typeof h.y === 'number') hl.push(h.y); }));
  [...new Set(hl)].slice(0, 6).forEach((y) =>
    L.push(`hline(${y}, "${y}", color=color.new(color.gray,40), linestyle=hline.style_dashed)`),
  );
  // TradingView rejects scripts beyond ~144KB — surface a truncation risk
  // instead of silently exporting a file that fails to compile (CR3 export audit).
  const bytes = new Blob([L.join('\n')]).size;
  if (bytes > 140_000)
    L.unshift(`// WARNING: ${Math.round(bytes / 1024)}KB exceeds the TradingView ~144KB script limit — lower ⚙→“TradingView export: bars” and re-export.`);
  downloadBlob(new Blob([L.join('\n')], { type: 'text/plain' }), `TASI_breadth_${safe(name)}.pine`);
}

